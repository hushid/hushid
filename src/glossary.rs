use std::io;
use std::path::Path;

/// Words the host wrote down.
///
/// A match uses a word boundary and the case on the line. The same
/// letters with every accent left off match too. A different accent
/// does not match.
#[derive(Clone, Debug)]
pub struct Glossary {
    terms: Vec<String>,
    pattern: Option<Regex>,
}

impl Default for Glossary {
    fn default() -> Self {
        Self::empty()
    }
}

impl Glossary {
    pub fn empty() -> Self {
        Self {
            terms: Vec::new(),
            pattern: None,
        }
    }

    pub fn from_terms<I, S>(terms: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: Into<String>,
    {
        let terms = terms
            .into_iter()
            .map(Into::into)
            .map(|term| term.trim().to_string())
            .filter(|term| !term.is_empty())
            .collect::<Vec<_>>();
        Self::from_vec(terms)
    }

    /// One entry per line. Blank lines and `#` comments are skipped.
    pub fn load(path: &Path) -> io::Result<Self> {
        let text = fs::read_to_string(path)?;
        Ok(Self::parse(&text))
    }

    /// The published USA, Canada, and Quebec name list, compiled into this crate.
    /// Shielding does not use it unless the host calls this function.
    pub fn popular_names() -> Self {
        Self::parse(include_str!("../glossary/popular-names.txt"))
    }

    fn parse(text: &str) -> Self {
        let mut terms = Vec::new();
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            terms.push(line.to_string());
        }
        Self::from_vec(terms)
    }

    pub fn terms(&self) -> &[String] {
        &self.terms
    }

    pub fn find(&self, text: &str) -> Vec<(usize, usize)> {
        let Some(pattern) = &self.pattern else {
            return Vec::new();
        };
        pattern
            .find_iter(text)
            .map(|hit| (hit.start(), hit.end()))
            .collect()
    }

    fn from_vec(terms: Vec<String>) -> Self {
        let pattern = compile(&terms);
        Self { terms, pattern }
    }
}

fn compile(terms: &[String]) -> Option<Regex> {
    if terms.is_empty() {
        return None;
    }
    let mut ordered = terms.to_vec();
    ordered.sort_by_key(|term| std::cmp::Reverse(term.len()));
    let body = ordered
        .iter()
        .map(|term| spellings(term))
        .collect::<Vec<_>>()
        .join("|");
    let pattern = format!(r"\b(?:{body})\b");
    Some(Regex::new(&pattern).expect("glossary names form a valid pattern"))
}

/// Exact spelling, the decomposed spelling, and every accent removed.
fn spellings(term: &str) -> String {
    let nfd = decompose(term);
    let nfc = compose(&nfd);
    let plain = strip_marks(&nfd);
    let mut forms = Vec::new();
    push_form(&mut forms, &nfc);
    push_form(&mut forms, &nfd);
    if !plain.is_empty() {
        push_form(&mut forms, &plain);
    }
    if forms.len() == 1 {
        forms.pop().unwrap()
    } else {
        format!("(?:{})", forms.join("|"))
    }
}

fn push_form(forms: &mut Vec<String>, text: &str) {
    let escaped = regex::escape(text);
    if !forms.contains(&escaped) {
        forms.push(escaped);
    }
}

fn decompose(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for ch in text.chars() {
        if let Some((base, marks)) = split_accent(ch) {
            out.push(base);
            out.extend(marks.iter().copied());
        } else {
            out.push(ch);
        }
    }
    out
}

fn compose(text: &str) -> String {
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::with_capacity(text.len());
    let mut index = 0;
    while index < chars.len() {
        let mut end = index + 1;
        while end < chars.len() && is_mark(chars[end]) {
            end += 1;
        }
        let marks = &chars[index + 1..end];
        if let Some(composed) = compose_cluster(chars[index], marks) {
            out.push(composed);
        } else {
            out.extend(chars[index..end].iter().copied());
        }
        index = end;
    }
    out
}

fn strip_marks(text: &str) -> String {
    text.chars().filter(|ch| !is_mark(*ch)).collect()
}

fn is_mark(ch: char) -> bool {
    matches!(
        ch,
        '\u{0300}'..='\u{036f}'
            | '\u{1ab0}'..='\u{1aff}'
            | '\u{1dc0}'..='\u{1dff}'
            | '\u{20d0}'..='\u{20ff}'
            | '\u{fe20}'..='\u{fe2f}'
    )
}

